"""Generate a structural helper-candidate catalogue; it never moves or edits source scripts."""
from collections import Counter
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
REPORT, SELF = ROOT / "scripts/helpers/catalog.md", Path(__file__).resolve()
PATTERNS = {
    ".py": r"^(?:async\s+)?def\s+(?P<name>[A-Za-z_]\w*)\s*\(",
    ".sh": r"^(?:function\s+)?(?P<name>[A-Za-z_][\w-]*)\s*\(\)",
    ".js": r"^(?:export\s+)?(?:async\s+)?(?:function|class)\s+(?P<name>\w+)\b|^(?:export\s+)?(?:const|let)\s+(?P<value>\w+)\s*=",
    ".mjs": r"^(?:export\s+)?(?:async\s+)?(?:function|class)\s+(?P<name>\w+)\b|^(?:export\s+)?(?:const|let)\s+(?P<value>\w+)\s*=",
    ".ts": r"^(?:export\s+)?(?:async\s+)?(?:function|class)\s+(?P<name>\w+)\b|^(?:export\s+)?(?:const|let)\s+(?P<value>\w+)\s*=",
}
NON_HELPER = re.compile(r"(^|/)(tests?|fixtures?)(/|$)|(?:^|[-_.])(test|fixture|smoke)(?:[-_.]|$)")


def source_files():
    return sorted(path for path in (ROOT / "scripts").rglob("*") if path.is_file() and path.suffix not in {".md", ".pyc"} and "__pycache__" not in path.parts and path.resolve() != SELF)


def snippets(path, text):
    pattern = PATTERNS.get(path.suffix, r"$^")
    return [(match.groupdict().get("name") or match.groupdict().get("value"), text.count("\n", 0, match.start()) + 1, match.group(0).strip()) for match in re.finditer(pattern, text, re.M)]


def evidence(path, found):
    location = path.relative_to(ROOT).as_posix()
    return (["shared location"] if "/shared/" in location else []) + (["library filename"] if path.name == "lib.sh" else []) + (["public export"] if any(item[2].startswith("export ") for item in found) else [])


def main():
    inspected, candidates = [], []
    for path in source_files():
        found = snippets(path, path.read_text(encoding="utf-8", errors="replace"))
        signals = evidence(path, found)
        inspected.append((path, found))
        if found and signals and not NON_HELPER.search(path.relative_to(ROOT).as_posix()):
            candidates.extend((path.relative_to(ROOT).as_posix(), *item, ", ".join(signals)) for item in found)
    counts = Counter(path.suffix or "[no extension]" for path, _ in inspected)
    lines = ["<!-- agentic-artifact:\n", "schema: agentic-artifact/v3\n", "id: repo.report.helpers-catalog\n", "version: 1\n", "status: draft\n", "created_on: \"2026-11-23\"\n", "updated_on: \"2026-11-23\"\n", "layer: 06.shared\n", "domain: scripts.catalogue\n", "disciplines: [architecture, agentic]\n", "kind: report\n", "purpose: Record structural helper candidates for manual extraction review.\n", "portability: {class: internal, targets: []}\n", "used_by:\n", "- id: repo.script.helpers.catalog\n", "  path: scripts/helpers/catalog.py\n", "-->\n\n", "# Helper-candidate catalogue\n\n", "This report is generated by `scripts/helpers/catalog.py`. It is a review list, not an extraction instruction or a check that runs during commits, merges, or deployment.\n\n", "## Scan result\n\n", f"- **Files read:** {len(inspected)} existing non-Markdown files under `scripts/` (the generator itself is excluded).\n", f"- **Candidate definitions:** {len(candidates)} across {len({row[0] for row in candidates})} files.\n", f"- **File types:** {', '.join(f'`{key}` {value}' for key, value in sorted(counts.items()))}.\n\n", "A candidate has named code plus a strong structural signal: it is already in a shared location, has a library filename, or exports a public JavaScript/TypeScript definition. Test, fixture, and smoke-test files are scanned but are not candidates. A human must still decide whether a definition is genuinely reusable; ordinary multi-function scripts are deliberately not listed yet.\n\n", "## Candidate definitions\n\n", "| File | Line | Definition | Structural signal |\n| --- | ---: | --- | --- |\n"]
    lines.extend(f"| `{path}` | {line} | `{signature.replace('|', '\\|')}` | {signals} |\n" for path, _name, line, signature, signals in candidates)
    REPORT.write_text("".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
